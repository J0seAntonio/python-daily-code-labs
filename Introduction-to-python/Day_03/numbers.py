# You can add (+), subtract (-), multiply (*), and divide (/) integers in Python.
addition = 2 + 3
print(f"Thhis is a addition (2+3):{addition}")

subtraction = 3 - 2
print(f"This is a subtraction (3-2):{subtraction}")

multiplication = 2 * 3
print(f"This is a multiplication (2*3):{multiplication}")

division = 3 / 2
print(f"This is a division (3/2):{division}")

# Exponents:
exponents = 3 * 2
print(exponents)

exponents = 3**3
print(exponents)

exponents = 10**6
print(exponents)


