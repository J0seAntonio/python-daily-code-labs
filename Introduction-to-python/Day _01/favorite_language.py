# Example of how to use the .rstrip(), lstrip(), strip()

# without any method
favorite_language = " python "
print(favorite_language)

# Using .rstrip():
print(f"using .rstrip():\n{favorite_language.rstrip()}")
# Using .lstrip()
print(f"Using .lstrip():\n{favorite_language.lstrip()}")
# Using .strip()
print(f"Using .lstrip():\n{favorite_language.strip()}")
